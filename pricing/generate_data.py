# -*- coding: utf-8 -*-
"""
Build the Egyptian raw-materials price dataset for the pricing model.

Data provenance (مصدر الداتا):
- Synthetic dataset generated by the team, anchored to PUBLIC market ranges
  observed in the Egyptian press (Nov 2026):
  * steel rebar (حديد تسليح): ~37k-40k EGP/ton
  * wood (خشب زان/سويد/موسكي): ~15.5k-33.5k EGP per m3 (per the market
    survey of 13 Nov 2026)
  * shredded plastic (بلاستيك مجروش): ~20k-30k EGP/ton
  plus typical trader prices for aluminium, copper, cement, sand, zalat
  and red brick.
- Each row = one historical ad/transaction: material, condition, unit,
  quantity, location, month, and the unit price in EGP.
- Prices follow a 24-month upward trend with seasonal noise and random
  market noise, multiplied by condition and location factors, so the
  regression model learns a realistic fair-price surface.

Output: pricing/data/prices.csv
"""
import csv
import math
import random
from pathlib import Path

random.seed(7)

OUT = Path(__file__).parent / "data"
OUT.mkdir(parents=True, exist_ok=True)

# canonical material -> (unit, base unit price EGP at month 0 = 2024-12)
MATERIALS = {
    "حديد تسليح": ("طن", 33000.0),
    "حديد خردة": ("طن", 15500.0),
    "خشب زان": ("متر مكعب", 29500.0),
    "خشب سويد": ("متر مكعب", 24000.0),
    "خشب موسكي": ("متر مكعب", 15500.0),
    "بلاستيك مجروش": ("طن", 21000.0),
    "ألومنيوم": ("طن", 92000.0),
    "نحاس": ("طن", 430000.0),
    "أسمنت": ("طن", 1950.0),
    "أسمنت أبيض": ("طن", 3600.0),
    "جبس": ("طن", 1350.0),
    "رمل": ("متر مكعب", 260.0),
    "زلط": ("متر مكعب", 320.0),
    "طوب أحمر": ("ألف", 2700.0),
    "طوب أبيض": ("ألف", 5200.0),
    "صاج": ("طن", 41000.0),
    "استانلس ستيل": ("طن", 138000.0),
    "رصاص": ("طن", 108000.0),
    "أبلكاش": ("لوح", 920.0),
    "MDF": ("لوح", 1280.0),
}

CONDITIONS = {  # multiplier range
    "جديد": (0.97, 1.05),
    "مستعمل": (0.62, 0.80),
    "صدأ": (0.40, 0.55),      # rusted / scrap condition
    "هالك": (0.30, 0.45),
}

LOCATIONS = {
    "القاهرة": 1.02, "الجيزة": 1.01, "الإسكندرية": 1.03, "المنصورة": 1.00,
    "طنطا": 0.99, "الزقازيق": 0.99, "السويس": 0.98, "بورسعيد": 1.00,
    "الإسماعيلية": 0.99, "أسيوط": 0.96, "المنيا": 0.96, "بنها": 1.00,
    "دمياط": 0.99, "المحلة": 1.00, "شبرا الخيمة": 1.01,
    "العاشر من رمضان": 1.00, "6 أكتوبر": 1.01, "حلوان": 1.00,
    "العبور": 1.00, "برج العرب": 1.02,
}

QTY_BY_UNIT = {
    "طن": [1, 2, 3, 5, 7, 10, 15, 20, 25, 30, 40, 50, 75, 100],
    "متر مكعب": [2, 3, 5, 7, 10, 12, 15, 20, 25, 30, 40, 50],
    "ألف": [3, 5, 7, 10, 15, 20, 25, 30, 40, 50, 75, 100, 150],
    "لوح": [5, 10, 15, 20, 25, 30, 40, 50, 75, 100, 150, 200],
}

MONTHS = [(y, m) for y in (2024, 2025, 2026)
          for m in range(1, 13) if (y, m) >= (2024, 12) and (y, m) <= (2026, 11)]


def trend(month_idx):
    # ~1.1% monthly compound drift + seasonal wave
    return (1.011 ** month_idx) * (1 + 0.02 * math.sin(month_idx / 12 * 2 * math.pi))


def main(n_rows=6000):
    rows = []
    for _ in range(n_rows):
        material, (unit, base) = random.choice(list(MATERIALS.items()))
        condition = random.choices(list(CONDITIONS), weights=[55, 25, 12, 8])[0]
        lo, hi = CONDITIONS[condition]
        cond_f = random.uniform(lo, hi)
        location = random.choice(list(LOCATIONS))
        loc_f = LOCATIONS[location]
        m_idx = random.randrange(len(MONTHS))
        year, month = MONTHS[m_idx]
        qty = random.choice(QTY_BY_UNIT[unit])
        # bulk discount: larger quantity -> slightly lower unit price
        qty_f = max(0.93, 1.0 - 0.0007 * qty)
        noise = random.lognormvariate(0.0, 0.045)
        price = base * trend(m_idx) * cond_f * loc_f * qty_f * noise
        rows.append({
            "material": material, "condition": condition, "unit": unit,
            "quantity": qty, "location": location,
            "year": year, "month": month,
            "unit_price_egp": round(price, 2),
        })
    rows.sort(key=lambda r: (r["year"], r["month"]))
    path = OUT / "prices.csv"
    with open(path, "w", newline="", encoding="utf-8-sig") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
    print(f"wrote {len(rows)} rows -> {path}")
    # quick sanity print of recent typical prices
    for material in ["حديد تسليح", "خشب زان", "بلاستيك مجروش", "أسمنت"]:
        recent = [r["unit_price_egp"] for r in rows
                  if r["material"] == material and r["condition"] == "جديد"
                  and r["year"] == 2026 and r["month"] >= 9]
        if recent:
            print(material, "جديد (2026-09..11): min={:.0f} max={:.0f}".format(
                min(recent), max(recent)))


if __name__ == "__main__":
    main()
